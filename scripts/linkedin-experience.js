// Renders cv/data/experience.json as paste-ready LinkedIn role text.
// CLI: node scripts/linkedin-experience.js   (CV_DIR defaults to ../cv)
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ENTITIES = { '&amp;': '&', '&lt;': '<', '&gt;': '>', '&quot;': '"', '&#39;': "'", '&nbsp;': ' ' };

export function htmlToText(html) {
  return String(html)
    .replace(/<a\s[^>]*href=["']([^"']*)["'][^>]*>([\s\S]*?)<\/a>/gi, (_, url, text) => `${text.replace(/<[^>]*>/g, '')} (${url})`)
    .replace(/<[^>]*>/g, '')
    .replace(/&(?:amp|lt|gt|quot|#39|nbsp);/g, (m) => ENTITIES[m])
    .replace(/\s+/g, ' ')
    .trim();
}

export function renderExperience(experience, cvSha) {
  const lines = [
    `<!-- Generated by make linkedin from cv ${cvSha}. Do not edit; change cv/data/experience.json. -->`,
    '',
    '# LinkedIn experience',
  ];
  for (const role of experience) {
    lines.push('', `## ${role.employer}, ${role.from} to ${role.to ?? 'present'}`, '');
    if (role.summary) lines.push(htmlToText(role.summary), '');
    for (const h of role.highlights ?? []) lines.push(`- ${htmlToText(h)}`);
  }
  return `${lines.join('\n').replace(/\n{3,}/g, '\n\n')}\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const cvDir = path.resolve(process.env.CV_DIR ?? '../cv');
  const experience = JSON.parse(fs.readFileSync(path.join(cvDir, 'data/experience.json'), 'utf8'));
  const git = (...a) => execFileSync('git', ['-C', cvDir, ...a], { encoding: 'utf8' }).trim();
  let sha = git('rev-parse', '--short', 'HEAD');
  if (git('status', '--porcelain', '--', 'data/experience.json')) sha += '+uncommitted';
  const out = path.join(path.dirname(fileURLToPath(import.meta.url)), '../profiles/linkedin/experience.md');
  fs.writeFileSync(out, renderExperience(experience, sha));
  console.log(`wrote ${path.relative(process.cwd(), out)} from cv ${sha}`);
}
