import { test } from 'node:test';
import assert from 'node:assert/strict';
import { renderExperience } from './linkedin-experience.js';

const fixture = [
  { employer: 'Acme', from: '2023-01-01', to: '2024-02-01', highlights: ['Did a thing.', 'Did another.'] },
  { employer: 'Beta', from: '2020-01-01', to: '2022-12-01', highlights: ['Built it.'] },
];

test('renders one section per role with its bullets', () => {
  const out = renderExperience(fixture, 'abc1234');
  const headings = out.split('\n').filter((l) => l.startsWith('## '));
  assert.equal(headings.length, 2);
  assert.match(headings[0], /Acme/);
  assert.match(headings[0], /2023-01-01 to 2024-02-01/);
  const bullets = out.split('\n').filter((l) => l.startsWith('- '));
  assert.deepEqual(bullets, ['- Did a thing.', '- Did another.', '- Built it.']);
});

test('strips HTML and keeps link URLs', () => {
  const out = renderExperience(
    [{ employer: 'X', from: '2020-01-01', to: '2021-01-01', highlights: [
      'Published <a href="https://www.npmjs.com/org/codesthings">npm plugins</a>',
    ] }],
    'abc1234',
  );
  assert.ok(out.includes('- Published npm plugins (https://www.npmjs.com/org/codesthings)'));
  assert.ok(!out.includes('<a'));
});

test('stamps the generated header', () => {
  const first = renderExperience(fixture, 'abc1234').split('\n')[0];
  assert.match(first, /Generated by make linkedin from cv/);
  assert.match(first, /abc1234/);
});
